package PracticeQuestions.Day2.Conditions.IfElse;

public class GreaterThan100 {
    public static void main(String[] args) {
        int number = 112;

        if (number > 100) {
            System.out.println("This number is Greater Than 100 : " +number);
        }
        else {
            System.out.println("This Number is Not Greater than 100 :" +number);
        }
    }
}
