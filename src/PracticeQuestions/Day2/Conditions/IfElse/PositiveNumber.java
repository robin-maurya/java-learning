package PracticeQuestions.Day2.Conditions.IfElse;

public class PositiveNumber {

    public static void main(String[] args) {

        int number = 10;

        if (number >= 0){
            System.out.println("This Number is Positive :" +number);
        } else {
            System.out.println("This number is Not Positive : " +number);
        }
    }
}
