package PracticeQuestions.Day1.Operators;

public class RectangleArea {
    public static void main(String[] args) {
        // for whole number
        System.out.println("int for whole number");
        int length = 6;
        int width = 8;

        int area = length * width;
        System.out.println("The area of the rectangle is: " + area);

        System.out.println();

        //double for decimal
        System.out.println("Double for decimal number");

        double lengthDec = 7.5;
        double widthDec = 5.9;

        double areaDec = lengthDec * widthDec;
        System.out.println("The area of the rectangle is: " + areaDec);

    }
}
