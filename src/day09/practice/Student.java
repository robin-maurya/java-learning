package day09.practice;

public class Student {
    private String name;
    private int age;

    // Setter for Name
    public void setName(String studentName) {
        name = studentName;
    }

    // Getter for Name
    public String getName() {
        return name;
    }

    // Setter for Age
    public void setAge(int studentAge) {
        age = studentAge;
    }

    // Getter for Age
    public int getAge() {
        return age;
    }
}
